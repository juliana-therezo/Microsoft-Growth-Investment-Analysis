   SYNTHETIC DATA, CALIBRATED TO MICROSOFT'S PUBLISHED RESULTS - generated by data/generate.py.

   Analysis window: the data runs Jan 2024 - Sep 2026.
     * FY24 is partial (Jan-Jun 2024) and FY27 is year to date (Jul-Sep 2026).
     * Full-year growth: FY26 vs FY25. Year-to-date growth: FY27 Q1 vs FY26 Q1.
     * Trailing 12 months (TTM) = Oct 2025 - Sep 2026. Base year = Jan - Dec 2024.
