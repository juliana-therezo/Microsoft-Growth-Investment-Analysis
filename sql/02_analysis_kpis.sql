       v_portfolio_region_fy26 ...... page 2 (sales regions, same framework)
       v_region_month ............... page 3 (cloud region P&L, capex and utilisation by month)
       v_region_returns ............. page 3 (return on capex, payback, NPV at 7 / 9 / 11%)
       v_budget_vs_actual ........... page 4 (by line item)
