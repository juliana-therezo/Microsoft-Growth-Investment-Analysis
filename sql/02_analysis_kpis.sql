/* -----------------------------------------------------------------------------
   0. Parameters - synthetic assumptions (keep in sync with config.py)
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_params AS
SELECT
    DATE '2024-01-01' AS data_start,
    DATE '2024-12-01' AS base_end,          -- base year for incremental returns: Jan - Dec 2024
    DATE '2025-10-01' AS ttm_start,         -- trailing 12 months: Oct 2025 - Sep 2026
    DATE '2026-09-01' AS data_end,
    0.09              AS hurdle_rate,
    0.07              AS hurdle_rate_low,
    0.11              AS hurdle_rate_high,
    15                AS life_years_build,  -- datacenter buildings
    6                 AS life_years_fleet,  -- servers and GPUs
    10                AS life_years_network,
    0.90              AS target_utilization;  -- utilisation a region is assumed to fill to


/* -----------------------------------------------------------------------------
   1. Revenue by month, product line and segment
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_revenue_monthly AS
SELECT
    b.revenue_month                             AS month_start,
    d.fiscal_year,
    d.fiscal_year_num,
    d.fiscal_quarter,
    d.fiscal_year_quarter,
    d.fiscal_period,
    b.segment_restated                          AS segment,
    b.product_line,
    SUM(b.net_value_usd)                        AS revenue_usd,
    SUM(CASE WHEN NOT b.is_credit_memo THEN b.quantity ELSE 0 END) AS quantity
FROM fact_billing AS b
JOIN dim_date     AS d ON d.calendar_date = b.revenue_month
GROUP BY ALL;


/* -----------------------------------------------------------------------------
   2. CFO overview: company KPIs by fiscal quarter, vs last year and vs budget
      Free cash flow (simplified) = operating income + depreciation - capex incl. finance leases
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_kpi_quarter AS
WITH months AS (
    SELECT DISTINCT month_start, fiscal_year_quarter FROM dim_date
),
revenue AS (
    SELECT m.fiscal_year_quarter, MIN(b.revenue_month) AS quarter_start, SUM(b.net_value_usd) AS revenue_usd
    FROM fact_billing AS b JOIN months AS m ON m.month_start = b.revenue_month
    GROUP BY 1
),
cost AS (
    SELECT m.fiscal_year_quarter,
           SUM(g.amount_usd)                                                    AS total_cost_usd,
           SUM(CASE WHEN g.functional_area = 'COGS' THEN g.amount_usd ELSE 0 END) AS cogs_usd,
           SUM(CASE WHEN g.gl_account = '500300' THEN g.amount_usd ELSE 0 END)    AS depreciation_usd
    FROM fact_gl_cost AS g JOIN months AS m ON m.month_start = g.month_start
    GROUP BY 1
),
capex AS (
    SELECT m.fiscal_year_quarter,
           SUM(c.capex_usd)               AS capex_usd,
           SUM(c.capex_finance_lease_usd) AS capex_finance_lease_usd
    FROM fact_datacenter AS c JOIN months AS m ON m.month_start = c.month_start
    GROUP BY 1
),
budget AS (
    SELECT m.fiscal_year_quarter,
           SUM(CASE WHEN line_item = 'Revenue' THEN amount_usd ELSE 0 END)           AS budget_revenue_usd,
           SUM(CASE WHEN line_item = 'Revenue' THEN amount_usd ELSE -amount_usd END) AS budget_operating_income_usd
    FROM fact_budget AS f JOIN months AS m ON m.month_start = f.month_start
    WHERE version = 'Budget'
    GROUP BY 1
),
combined AS (
    SELECT
        r.fiscal_year_quarter,
        r.quarter_start,
        r.revenue_usd,
        r.revenue_usd - c.cogs_usd                     AS gross_profit_usd,
        r.revenue_usd - c.total_cost_usd               AS operating_income_usd,
        c.depreciation_usd,
        x.capex_usd,
        x.capex_finance_lease_usd,
        b.budget_revenue_usd,
        b.budget_operating_income_usd
    FROM revenue AS r
    LEFT JOIN cost   AS c USING (fiscal_year_quarter)
    LEFT JOIN capex  AS x USING (fiscal_year_quarter)
    LEFT JOIN budget AS b USING (fiscal_year_quarter)
)
SELECT
    *,
    gross_profit_usd / NULLIF(revenue_usd, 0)                                AS gross_margin,
    operating_income_usd / NULLIF(revenue_usd, 0)                            AS operating_margin,
    revenue_usd / NULLIF(LAG(revenue_usd, 4) OVER (ORDER BY quarter_start), 0) - 1 AS revenue_growth_yoy,
    capex_finance_lease_usd / NULLIF(capex_usd, 0)                           AS lease_share_of_capex,
    operating_income_usd + depreciation_usd - capex_usd                      AS free_cash_flow_usd,
    revenue_usd - budget_revenue_usd                                         AS revenue_vs_budget_usd,
    operating_income_usd - budget_operating_income_usd                       AS operating_income_vs_budget_usd
FROM combined
ORDER BY quarter_start;


/* -----------------------------------------------------------------------------
   3. Profitability by fiscal year and product line
      Direct costs come from the GL by profit centre. Corporate G&A (PC-CORP)
      is allocated to product lines by their share of revenue in that year.
      Growth is only compared like for like:
        revenue_growth     = full fiscal year: 12 months vs the previous 12 months
                             (both years must be complete)
        revenue_growth_ytd = incomplete year (FY27 = Jul-Sep 2026) vs the same
                             months one year earlier (Jul-Sep 2025)
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_profitability_fy AS
WITH fy_months AS (            -- months of data in each fiscal year (FY24 = 6, FY27 = 3)
    SELECT fiscal_year, COUNT(DISTINCT month_start) AS months_in_data
    FROM v_revenue_monthly
    GROUP BY 1
),
revenue AS (
    SELECT r.fiscal_year, r.fiscal_year_num, r.product_line, f.months_in_data,
           SUM(r.revenue_usd)                   AS revenue_usd
    FROM v_revenue_monthly AS r
    JOIN fy_months         AS f ON f.fiscal_year = r.fiscal_year
    GROUP BY 1, 2, 3, 4
),
prior_same_months AS (       -- revenue of the same months one year earlier (for YTD growth)
    SELECT cur.fiscal_year, cur.product_line,
           SUM(prev.revenue_usd)                AS revenue_py_same_months_usd
    FROM (SELECT DISTINCT fiscal_year, product_line, month_start FROM v_revenue_monthly) AS cur
    JOIN v_revenue_monthly AS prev
      ON prev.product_line = cur.product_line
     AND prev.month_start  = cur.month_start - INTERVAL 12 MONTH
    GROUP BY 1, 2
),
direct_cost AS (
    SELECT d.fiscal_year, g.product_line,
           SUM(CASE WHEN g.functional_area = 'COGS' THEN g.amount_usd ELSE 0 END) AS cogs_usd,
           SUM(CASE WHEN g.functional_area = 'R&D'  THEN g.amount_usd ELSE 0 END) AS rnd_usd,
           SUM(CASE WHEN g.functional_area = 'S&M'  THEN g.amount_usd ELSE 0 END) AS snm_usd
    FROM fact_gl_cost AS g
    JOIN dim_date     AS d ON d.calendar_date = g.month_start
    WHERE g.product_line <> 'Corporate'
    GROUP BY 1, 2
),
corporate_ga AS (
    SELECT d.fiscal_year, SUM(g.amount_usd)     AS ga_usd
    FROM fact_gl_cost AS g
    JOIN dim_date     AS d ON d.calendar_date = g.month_start
    WHERE g.product_line = 'Corporate'
    GROUP BY 1
),
combined AS (
    SELECT
        r.fiscal_year,
        r.fiscal_year_num,
        r.product_line,
        p.segment_restated                      AS segment,
        r.months_in_data,
        r.revenue_usd,
        dc.cogs_usd,
        dc.rnd_usd,
        dc.snm_usd,
        ga.ga_usd * r.revenue_usd / SUM(r.revenue_usd) OVER (PARTITION BY r.fiscal_year) AS ga_allocated_usd,
        pm.revenue_py_same_months_usd
    FROM revenue AS r
    JOIN (SELECT DISTINCT product_line, segment_restated FROM dim_product_line) AS p ON p.product_line = r.product_line
    LEFT JOIN direct_cost  AS dc ON dc.fiscal_year = r.fiscal_year AND dc.product_line = r.product_line
    LEFT JOIN corporate_ga AS ga ON ga.fiscal_year = r.fiscal_year
    LEFT JOIN prior_same_months AS pm ON pm.fiscal_year = r.fiscal_year AND pm.product_line = r.product_line
)
SELECT
    *,
    revenue_usd - cogs_usd                                              AS gross_profit_usd,
    revenue_usd - cogs_usd - rnd_usd - snm_usd - ga_allocated_usd       AS operating_income_usd,
    (revenue_usd - cogs_usd) / NULLIF(revenue_usd, 0)                   AS gross_margin,
    (revenue_usd - cogs_usd - rnd_usd - snm_usd - ga_allocated_usd)
        / NULLIF(revenue_usd, 0)                                        AS operating_margin,
    -- full-year growth only when BOTH years have 12 months of data (FY24 and FY27 are partial)
    CASE WHEN months_in_data = 12 AND LAG(months_in_data) OVER w = 12
         THEN revenue_usd / NULLIF(LAG(revenue_usd) OVER w, 0) - 1 END AS revenue_growth,
    -- year-to-date growth for an incomplete year: same months, one year apart
    CASE WHEN months_in_data < 12
         THEN revenue_usd / NULLIF(revenue_py_same_months_usd, 0) - 1 END AS revenue_growth_ytd,
    -- operating leverage: opex growth / revenue growth (< 1 = costs grow slower than revenue)
    CASE WHEN months_in_data = 12 AND LAG(months_in_data) OVER w = 12
         THEN ((rnd_usd + snm_usd + ga_allocated_usd)
                 / NULLIF(LAG(rnd_usd + snm_usd + ga_allocated_usd) OVER w, 0) - 1)
              / NULLIF(revenue_usd / NULLIF(LAG(revenue_usd) OVER w, 0) - 1, 0) END AS operating_leverage
FROM combined
WINDOW w AS (PARTITION BY product_line ORDER BY fiscal_year_num);


/* -----------------------------------------------------------------------------
   3b. Profitability by segment (restated, so FY25 and FY26 are like for like)
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_profitability_segment_fy AS
SELECT
    fiscal_year,
    segment,
    SUM(revenue_usd)                                                   AS revenue_usd,
    SUM(gross_profit_usd)                                              AS gross_profit_usd,
    SUM(operating_income_usd)                                          AS operating_income_usd,
    SUM(gross_profit_usd) / NULLIF(SUM(revenue_usd), 0)                AS gross_margin,
    SUM(operating_income_usd) / NULLIF(SUM(revenue_usd), 0)            AS operating_margin
FROM v_profitability_fy
GROUP BY 1, 2;


/* -----------------------------------------------------------------------------
   3c. Segment revenue: as reported vs restated (Windows Commercial moved to
       Productivity and Business Processes on 1 Jul 2025)
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_segment_revenue_fy AS
SELECT
    d.fiscal_year,
    b.segment_as_reported,
    b.segment_restated,
    SUM(b.net_value_usd)                         AS revenue_usd
FROM fact_billing AS b
JOIN dim_date     AS d ON d.calendar_date = b.revenue_month
GROUP BY 1, 2, 3;


/* -----------------------------------------------------------------------------
   4. Portfolio map, last complete year (FY26): growth x operating margin
      High growth = above the MEDIAN growth of the peers (product lines vs product lines).
      High margin = above the COMPANY-WIDE operating margin of the same year.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_portfolio_fy26 AS
WITH fy26 AS (
    SELECT product_line, segment, revenue_usd, operating_income_usd, operating_margin, revenue_growth,
           MEDIAN(revenue_growth) OVER ()                               AS median_growth,
           SUM(operating_income_usd) OVER () / SUM(revenue_usd) OVER () AS company_margin
    FROM v_profitability_fy
    WHERE fiscal_year = 'FY26'
)
SELECT
    *,
    CASE
        WHEN revenue_growth >  median_growth AND operating_margin >  company_margin THEN 'Invest'
        WHEN revenue_growth >  median_growth AND operating_margin <= company_margin THEN 'Optimise'
        WHEN revenue_growth <= median_growth AND operating_margin >  company_margin THEN 'Maintain'
        ELSE 'Deprioritise'
    END                                          AS portfolio_action
FROM fy26;

-- Same framework for sales regions (Americas, EMEA, APAC) and sales areas.
-- Revenue comes from the billing country. Costs are not booked by customer country, so each
-- product line's operating margin is applied to that line's revenue in the region (a fixed key).
CREATE OR REPLACE VIEW v_portfolio_region_fy26 AS
WITH geo AS (
    SELECT d.fiscal_year, r.sales_region, r.sales_area, b.product_line, SUM(b.net_value_usd) AS revenue_usd
    FROM fact_billing AS b
    JOIN dim_region   AS r USING (country_key)
    JOIN dim_date     AS d ON d.calendar_date = b.revenue_month
    WHERE d.fiscal_year IN ('FY25', 'FY26')
    GROUP BY ALL
),
geo_oi AS (
    SELECT g.*, g.revenue_usd * p.operating_margin AS operating_income_usd
    FROM geo AS g
    JOIN v_profitability_fy AS p ON p.fiscal_year = g.fiscal_year AND p.product_line = g.product_line
),
levels AS (
    SELECT 'Sales region' AS level, sales_region AS region, fiscal_year,
           SUM(revenue_usd) AS revenue_usd, SUM(operating_income_usd) AS operating_income_usd
    FROM geo_oi GROUP BY ALL
    UNION ALL
    SELECT 'Sales area', sales_area, fiscal_year, SUM(revenue_usd), SUM(operating_income_usd)
    FROM geo_oi GROUP BY ALL
),
fy26 AS (
    SELECT
        c.level, c.region, c.revenue_usd, c.operating_income_usd,
        c.operating_income_usd / NULLIF(c.revenue_usd, 0)  AS operating_margin,
        c.revenue_usd / NULLIF(p.revenue_usd, 0) - 1       AS revenue_growth
    FROM levels AS c
    JOIN levels AS p ON p.level = c.level AND p.region = c.region AND p.fiscal_year = 'FY25'
    WHERE c.fiscal_year = 'FY26'
),
cut AS (
    SELECT *,
           MEDIAN(revenue_growth) OVER (PARTITION BY level) AS median_growth,
           (SELECT SUM(operating_income_usd) / SUM(revenue_usd) FROM v_profitability_fy WHERE fiscal_year = 'FY26') AS company_margin
    FROM fy26
)
SELECT
    *,
    CASE
        WHEN revenue_growth >  median_growth AND operating_margin >  company_margin THEN 'Invest'
        WHEN revenue_growth >  median_growth AND operating_margin <= company_margin THEN 'Optimise'
        WHEN revenue_growth <= median_growth AND operating_margin >  company_margin THEN 'Maintain'
        ELSE 'Deprioritise'
    END                                          AS portfolio_action
FROM cut;


/* -----------------------------------------------------------------------------
   5. Cloud regions by month: Azure P&L, capex and capacity
      Operating income after depreciation
          = Azure revenue billed in the region
          - the region's datacenter costs (power, operations, staff, contractors)
          - depreciation of the region's datacenter assets
          - the region's share of Azure overhead: Azure R&D and S&M, plus Azure's share
            of corporate G&A (corporate G&A x Azure's share of company revenue).
            Each pool is spread over regions by the region's share of Azure revenue
            in that month (an explainable key, not a measure of actual resource use).
      Operating cash flow = operating income + depreciation.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_region_month AS
WITH revenue AS (
    SELECT revenue_month AS month_start, region_code, SUM(net_value_usd) AS azure_revenue_usd
    FROM fact_billing
    WHERE product_line = 'Azure'
    GROUP BY 1, 2
),
company_revenue AS (
    SELECT revenue_month AS month_start,
           SUM(net_value_usd)                                                         AS company_revenue_usd,
           SUM(CASE WHEN product_line = 'Azure' THEN net_value_usd ELSE 0 END)        AS azure_total_usd
    FROM fact_billing
    GROUP BY 1
),
dc_cost AS (
    SELECT month_start, region_code,
           SUM(CASE WHEN gl_account <> '500300' THEN amount_usd ELSE 0 END) AS dc_operating_cost_usd,
           SUM(CASE WHEN gl_account =  '500300' THEN amount_usd ELSE 0 END) AS depreciation_usd
    FROM fact_gl_cost
    WHERE region_code IS NOT NULL
    GROUP BY 1, 2
),
overhead AS (          -- Azure R&D, S&M and Azure costs without a region; corporate G&A
    SELECT month_start,
           SUM(CASE WHEN product_line = 'Azure' AND region_code IS NULL THEN amount_usd ELSE 0 END) AS azure_shared_usd,
           SUM(CASE WHEN product_line = 'Corporate' THEN amount_usd ELSE 0 END)                   AS corporate_ga_usd
    FROM fact_gl_cost
    GROUP BY 1
)
SELECT
    d.region_code,
    cr.region_name,
    cr.sales_region,
    d.month_start,
    COALESCE(r.azure_revenue_usd, 0)                                        AS azure_revenue_usd,
    COALESCE(c.dc_operating_cost_usd, 0)                                    AS dc_operating_cost_usd,
    COALESCE(c.depreciation_usd, 0)                                         AS depreciation_usd,
    COALESCE(r.azure_revenue_usd, 0) / NULLIF(t.azure_total_usd, 0)
        * (o.azure_shared_usd + o.corporate_ga_usd * t.azure_total_usd / NULLIF(t.company_revenue_usd, 0))
                                                                            AS allocated_overhead_usd,
    COALESCE(r.azure_revenue_usd, 0) - COALESCE(c.dc_operating_cost_usd, 0) - COALESCE(c.depreciation_usd, 0)
        - COALESCE(r.azure_revenue_usd, 0) / NULLIF(t.azure_total_usd, 0)
          * (o.azure_shared_usd + o.corporate_ga_usd * t.azure_total_usd / NULLIF(t.company_revenue_usd, 0))
                                                                            AS operating_income_usd,
    d.capex_usd,
    d.capex_build_usd,
    d.capex_fleet_usd,
    d.capex_network_usd,
    d.capex_finance_lease_usd,
    d.capex_owned_usd,
    d.installed_mw,
    d.used_mw,
    d.utilization,
    d.new_capacity_mw
FROM fact_datacenter AS d
JOIN dim_cloud_region     AS cr USING (region_code)
LEFT JOIN revenue         AS r  ON r.region_code = d.region_code AND r.month_start = d.month_start
LEFT JOIN dc_cost         AS c  ON c.region_code = d.region_code AND c.month_start = d.month_start
LEFT JOIN company_revenue AS t  ON t.month_start = d.month_start
LEFT JOIN overhead        AS o  ON o.month_start = d.month_start;


/* -----------------------------------------------------------------------------
   6. Return on datacenter capex by cloud region
      Two views of the same capex (Jan 2024 - Sep 2026):
      a) Realised so far - incremental = TTM (Oct 2025 - Sep 2026) minus the base year
         (Jan - Dec 2024):
           realised return on capex = incremental operating income after depreciation / capex
         Capacity that is still filling up (or still being built) is in the denominator,
         so this view understates young regions - the 6-18 month lag in the project plan.
      b) Once capacity fills - what the capacity added since 2024 earns at the region's
         current economics:
           cash flow per used MW   = TTM operating cash flow (operating income + depreciation)
                                     / average used MW in the TTM
           steady-state cash flow  = cash flow per used MW x MW added x target utilisation (90%)
           steady-state return     = (steady-state cash flow - depreciation of the new capex)
                                     / capex
           payback (years)         = capex / steady-state cash flow
           NPV                     = steady-state cash flow x annuity factor - capex,
                                     at 7%, 9% (hurdle) and 11%; annuity = (1 - (1 + r)^-n) / r
           useful life (n)         = capex-weighted: buildings 15, fleet 6, network 10 years
      Capex rule: a region earns its cost when NPV at 9% > 0 and payback <= useful life.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_region_returns AS
WITH agg AS (
    SELECT
        m.region_code,
        ANY_VALUE(m.region_name)                                                          AS region_name,
        ANY_VALUE(m.sales_region)                                                         AS sales_region,
        SUM(m.capex_usd)                                                                  AS capex_usd,
        SUM(m.capex_finance_lease_usd)                                                    AS capex_finance_lease_usd,
        SUM(m.capex_build_usd)                                                            AS capex_build_usd,
        SUM(m.capex_fleet_usd)                                                            AS capex_fleet_usd,
        SUM(m.capex_network_usd)                                                          AS capex_network_usd,
        SUM(m.new_capacity_mw)                                                            AS mw_added,
        MAX(CASE WHEN m.month_start = p.data_end THEN m.installed_mw END)                 AS installed_mw,
        MAX(CASE WHEN m.month_start = p.data_end THEN m.utilization END)                  AS utilization_now,
        MAX(CASE WHEN m.month_start = p.data_end - INTERVAL 12 MONTH THEN m.utilization END) AS utilization_12m_ago,
        SUM(CASE WHEN m.month_start >= p.ttm_start THEN m.azure_revenue_usd END)          AS revenue_ttm_usd,
        SUM(CASE WHEN m.month_start <= p.base_end  THEN m.azure_revenue_usd END)          AS revenue_base_usd,
        SUM(CASE WHEN m.month_start >= p.ttm_start THEN m.operating_income_usd END)       AS operating_income_ttm_usd,
        SUM(CASE WHEN m.month_start <= p.base_end  THEN m.operating_income_usd END)       AS operating_income_base_usd,
        SUM(CASE WHEN m.month_start >= p.ttm_start THEN m.depreciation_usd END)           AS depreciation_ttm_usd,
        SUM(CASE WHEN m.month_start <= p.base_end  THEN m.depreciation_usd END)           AS depreciation_base_usd,
        AVG(CASE WHEN m.month_start >= p.ttm_start THEN m.used_mw END)                    AS used_mw_ttm,
        ANY_VALUE(p.target_utilization)                                                   AS target_utilization,
        ANY_VALUE(p.hurdle_rate) AS r9, ANY_VALUE(p.hurdle_rate_low) AS r7, ANY_VALUE(p.hurdle_rate_high) AS r11,
        ANY_VALUE(p.life_years_build) AS lb, ANY_VALUE(p.life_years_fleet) AS lf, ANY_VALUE(p.life_years_network) AS ln
    FROM v_region_month AS m
    CROSS JOIN v_params AS p
    GROUP BY m.region_code
),
calc AS (
    SELECT
        *,
        operating_income_ttm_usd / NULLIF(revenue_ttm_usd, 0)                   AS operating_margin_ttm,
        operating_income_ttm_usd - operating_income_base_usd                    AS incremental_operating_income_usd,
        (operating_income_ttm_usd + depreciation_ttm_usd)
          - (operating_income_base_usd + depreciation_base_usd)                 AS incremental_cash_flow_usd,
        capex_finance_lease_usd / NULLIF(capex_usd, 0)                          AS lease_share_of_capex,
        (capex_build_usd * lb + capex_fleet_usd * lf + capex_network_usd * ln)
          / NULLIF(capex_usd, 0)                                                AS useful_life_years,
        (operating_income_ttm_usd + depreciation_ttm_usd) / NULLIF(used_mw_ttm, 0) AS cash_flow_per_used_mw_usd,
        (operating_income_ttm_usd + depreciation_ttm_usd) / NULLIF(used_mw_ttm, 0)
          * mw_added * target_utilization                                       AS steady_state_cash_flow_usd,
        capex_build_usd / lb + capex_fleet_usd / lf + capex_network_usd / ln    AS new_capex_depreciation_usd
    FROM agg
),
npv AS (
    SELECT
        *,
        incremental_operating_income_usd / NULLIF(capex_usd, 0)                 AS realised_return_on_capex,
        (steady_state_cash_flow_usd - new_capex_depreciation_usd) / NULLIF(capex_usd, 0) AS return_on_capex,
        CASE WHEN steady_state_cash_flow_usd > 0
             THEN capex_usd / steady_state_cash_flow_usd END                    AS payback_years,
        steady_state_cash_flow_usd * (1 - POWER(1 + r7,  -useful_life_years)) / r7  - capex_usd AS npv_7_usd,
        steady_state_cash_flow_usd * (1 - POWER(1 + r9,  -useful_life_years)) / r9  - capex_usd AS npv_9_usd,
        steady_state_cash_flow_usd * (1 - POWER(1 + r11, -useful_life_years)) / r11 - capex_usd AS npv_11_usd
    FROM calc
)
SELECT
    region_code, region_name, sales_region,
    installed_mw, mw_added, utilization_now, utilization_now - utilization_12m_ago AS utilization_change_12m,
    revenue_ttm_usd, operating_income_ttm_usd, operating_margin_ttm,
    capex_usd, capex_finance_lease_usd, lease_share_of_capex,
    incremental_operating_income_usd, realised_return_on_capex,
    cash_flow_per_used_mw_usd, steady_state_cash_flow_usd,
    return_on_capex, payback_years, useful_life_years,
    npv_7_usd, npv_9_usd, npv_11_usd,
    COALESCE(npv_9_usd > 0 AND payback_years <= useful_life_years, false) AS earns_its_cost,
    (npv_7_usd > 0) <> (npv_11_usd > 0)                                    AS verdict_changes_7_vs_11,
    RANK() OVER (ORDER BY return_on_capex DESC NULLS LAST)                 AS return_rank
FROM npv
ORDER BY return_rank;


/* -----------------------------------------------------------------------------
   7. Budget vs actual by fiscal year, product line and line item
      Only months with actuals are compared (FY27 = Jul-Sep 2026 year to date).
      G&A actuals are corporate costs allocated by revenue share (as in view 3).
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_budget_vs_actual AS
WITH actual AS (
    SELECT fiscal_year, product_line, 'Revenue'                    AS line_item, revenue_usd      AS actual_usd FROM v_profitability_fy
    UNION ALL
    SELECT fiscal_year, product_line, 'Cost of Revenue',                      cogs_usd                         FROM v_profitability_fy
    UNION ALL
    SELECT fiscal_year, product_line, 'Research and Development',             rnd_usd                          FROM v_profitability_fy
    UNION ALL
    SELECT fiscal_year, product_line, 'Sales and Marketing',                  snm_usd                          FROM v_profitability_fy
    UNION ALL
    SELECT fiscal_year, product_line, 'General and Administrative',           ga_allocated_usd                 FROM v_profitability_fy
),
budget AS (
    SELECT fiscal_year, product_line, line_item,
           SUM(CASE WHEN version = 'Budget'       THEN amount_usd END) AS budget_usd,
           SUM(CASE WHEN version = 'Forecast 6+6' THEN amount_usd END) AS forecast_6_6_usd
    FROM fact_budget
    WHERE month_start <= (SELECT data_end FROM v_params)
    GROUP BY 1, 2, 3
)
SELECT
    b.fiscal_year,
    p.segment_restated                                      AS segment,
    b.product_line,
    b.line_item,
    b.budget_usd,
    b.forecast_6_6_usd,
    a.actual_usd,
    a.actual_usd - b.budget_usd                             AS variance_usd,
    a.actual_usd / NULLIF(b.budget_usd, 0) - 1              AS variance_pct,
    -- favourable = more revenue or less cost than budget
    CASE WHEN (b.line_item = 'Revenue' AND a.actual_usd >= b.budget_usd)
           OR (b.line_item <> 'Revenue' AND a.actual_usd <= b.budget_usd)
         THEN 'Favourable' ELSE 'Unfavourable' END          AS variance_direction
FROM budget AS b
JOIN (SELECT DISTINCT product_line, segment_restated FROM dim_product_line) AS p ON p.product_line = b.product_line
LEFT JOIN actual AS a
       ON a.fiscal_year = b.fiscal_year AND a.product_line = b.product_line AND a.line_item = b.line_item;


/* -----------------------------------------------------------------------------
   7b. Operating-income bridge: budget -> volume -> price/mix -> cost -> actual
       FY26 full year and FY27 year to date, by product line.
       The plan has no volumes, so budget volume = budget revenue / last year's average
       price per unit (p0) for the same months.
         volume    = (actual units - budget units) x p0   = actual units x p0 - budget revenue
         price/mix = actual revenue - actual units x p0
         cost      = budget costs - actual costs (positive = under budget)
       The four steps add up exactly: budget OI + volume + price/mix + cost = actual OI.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_budget_bridge AS
WITH actual AS (
    SELECT fiscal_year_num, fiscal_period, product_line,
           SUM(revenue_usd) AS revenue_usd, SUM(quantity) AS quantity
    FROM v_revenue_monthly
    GROUP BY 1, 2, 3
),
prior AS (
    SELECT fiscal_year_num + 1 AS fiscal_year_num, fiscal_period, product_line,
           revenue_usd AS py_revenue_usd, quantity AS py_quantity
    FROM actual
),
actual_cost AS (
    SELECT g.fiscal_year_num, g.fiscal_period, g.product_line, SUM(g.amount_usd) AS cost_usd
    FROM fact_gl_cost AS g
    WHERE g.product_line <> 'Corporate'
    GROUP BY 1, 2, 3
),
corporate AS (           -- corporate G&A allocated by revenue share of the month
    SELECT a.fiscal_year_num, a.fiscal_period, a.product_line,
           c.ga_usd * a.revenue_usd / SUM(a.revenue_usd) OVER (PARTITION BY a.fiscal_year_num, a.fiscal_period) AS ga_usd
    FROM actual AS a
    JOIN (SELECT fiscal_year_num, fiscal_period, SUM(amount_usd) AS ga_usd
          FROM fact_gl_cost WHERE product_line = 'Corporate' GROUP BY 1, 2) AS c
      USING (fiscal_year_num, fiscal_period)
),
budget AS (
    SELECT d.fiscal_year_num, d.fiscal_period, f.product_line,
           SUM(CASE WHEN f.line_item = 'Revenue' THEN f.amount_usd ELSE 0 END)  AS budget_revenue_usd,
           SUM(CASE WHEN f.line_item <> 'Revenue' THEN f.amount_usd ELSE 0 END) AS budget_cost_usd
    FROM fact_budget AS f
    JOIN (SELECT DISTINCT month_start, fiscal_year_num, fiscal_period FROM dim_date) AS d USING (month_start)
    WHERE f.version = 'Budget'
    GROUP BY 1, 2, 3
),
joined AS (
    SELECT
        'FY' || right(CAST(a.fiscal_year_num AS VARCHAR), 2)
            || CASE WHEN MAX(a.fiscal_period) < 12 THEN ' YTD' ELSE '' END   AS period,
        a.product_line,
        SUM(a.revenue_usd)                                 AS revenue_usd,
        SUM(a.quantity)                                    AS quantity,
        SUM(py.py_revenue_usd) / NULLIF(SUM(py.py_quantity), 0) AS py_price_per_unit,
        SUM(b.budget_revenue_usd)                          AS budget_revenue_usd,
        SUM(b.budget_cost_usd)                             AS budget_cost_usd,
        SUM(c.cost_usd + COALESCE(g.ga_usd, 0))            AS actual_cost_usd
    FROM actual AS a
    JOIN prior       AS py USING (fiscal_year_num, fiscal_period, product_line)
    JOIN budget      AS b  USING (fiscal_year_num, fiscal_period, product_line)
    JOIN actual_cost AS c  USING (fiscal_year_num, fiscal_period, product_line)
    LEFT JOIN corporate AS g USING (fiscal_year_num, fiscal_period, product_line)
    WHERE a.fiscal_year_num IN (2026, 2027)
    GROUP BY a.fiscal_year_num, a.product_line
)
SELECT
    period,
    product_line,
    budget_revenue_usd - budget_cost_usd                                AS budget_operating_income_usd,
    COALESCE(quantity * py_price_per_unit, revenue_usd) - budget_revenue_usd AS volume_effect_usd,
    revenue_usd - COALESCE(quantity * py_price_per_unit, revenue_usd)   AS price_mix_effect_usd,
    budget_cost_usd - actual_cost_usd                                   AS cost_effect_usd,
    revenue_usd - actual_cost_usd                                       AS actual_operating_income_usd,
    revenue_usd, budget_revenue_usd, actual_cost_usd, budget_cost_usd, quantity, py_price_per_unit
FROM joined
ORDER BY period, product_line;


/* -----------------------------------------------------------------------------
   8. Pipeline conversion: deals closed in the last 12 months (Oct 2025 - Sep 2026)
      New Business -> win rate; Renewal -> renewal rate. Sales cycle = created to close.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_pipeline_conversion AS
SELECT
    o.opportunity_type,
    o.customer_type,
    r.sales_region,
    o.product_line,
    SUM(CASE WHEN o.status = 'Won'  THEN 1 ELSE 0 END)                        AS won,
    SUM(CASE WHEN o.status = 'Lost' THEN 1 ELSE 0 END)                        AS lost,
    SUM(CASE WHEN o.status = 'Won'  THEN 1 ELSE 0 END) * 1.0 / COUNT(*)       AS conversion_rate,
    SUM(CASE WHEN o.status = 'Won'  THEN o.est_revenue_usd ELSE 0 END)
        / NULLIF(SUM(o.est_revenue_usd), 0)                                   AS value_conversion_rate,
    AVG(CASE WHEN o.status = 'Won'  THEN o.est_revenue_usd END)               AS avg_won_deal_usd,
    AVG(o.sales_cycle_days)                                                   AS avg_sales_cycle_days
FROM fact_opportunity AS o
JOIN dim_region       AS r ON r.country_key = o.country_key
WHERE o.status IN ('Won', 'Lost')
  AND o.close_date BETWEEN DATE '2025-10-01' AND DATE '2026-09-30'
GROUP BY 1, 2, 3, 4;

-- Win rate by sales region: new-business deals closed in the last 12 months
CREATE OR REPLACE VIEW v_win_rate_region AS
SELECT
    sales_region,
    SUM(won)                                    AS won,
    SUM(lost)                                   AS lost,
    SUM(won) * 1.0 / NULLIF(SUM(won) + SUM(lost), 0) AS win_rate
FROM v_pipeline_conversion
WHERE opportunity_type = 'New Business'
GROUP BY 1;


/* -----------------------------------------------------------------------------
   9. Pipeline coverage for next quarter (Q2 FY27, Oct-Dec 2026), by product line
        gap                = Q2 FY27 budget revenue - Q1 FY27 actual revenue (the run-rate
                             the business already bills)
        weighted pipeline  = open deals closing in Q2 FY27 x probability (annual contract value)
        revenue in quarter = weighted pipeline x months billed in Q2 after the close / 12
                             (Oct close -> 2 months, Nov -> 1, Dec -> 0)
        coverage           = revenue in quarter / gap   (no ratio when there is no gap)
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_pipeline_coverage AS
WITH target AS (
    SELECT product_line, SUM(amount_usd) AS q2_budget_revenue_usd
    FROM fact_budget
    WHERE version = 'Budget' AND line_item = 'Revenue'
      AND month_start BETWEEN DATE '2026-10-01' AND DATE '2026-12-01'
    GROUP BY 1
),
run_rate AS (
    SELECT product_line, SUM(revenue_usd) AS q1_actual_revenue_usd
    FROM v_revenue_monthly
    WHERE fiscal_year_quarter = 'FY27-Q1'
    GROUP BY 1
),
open_q2 AS (
    SELECT product_line,
           COUNT(*)                                                    AS open_opportunities,
           SUM(est_revenue_usd)                                        AS open_pipeline_usd,
           SUM(weighted_revenue_usd)                                   AS weighted_pipeline_usd,
           SUM(weighted_revenue_usd * (12 - month(close_date)) / 12.0) AS weighted_revenue_in_quarter_usd
    FROM fact_opportunity
    WHERE status = 'Open' AND close_date BETWEEN DATE '2026-10-01' AND DATE '2026-12-31'
    GROUP BY 1
),
lines AS (
    SELECT
        t.product_line,
        t.q2_budget_revenue_usd,
        COALESCE(r.q1_actual_revenue_usd, 0)                           AS q1_actual_revenue_usd,
        t.q2_budget_revenue_usd - COALESCE(r.q1_actual_revenue_usd, 0) AS gap_usd,
        COALESCE(o.open_opportunities, 0)                              AS open_opportunities,
        COALESCE(o.open_pipeline_usd, 0)                               AS open_pipeline_usd,
        COALESCE(o.weighted_pipeline_usd, 0)                           AS weighted_pipeline_usd,
        COALESCE(o.weighted_revenue_in_quarter_usd, 0)                 AS weighted_revenue_in_quarter_usd
    FROM target AS t
    LEFT JOIN run_rate AS r USING (product_line)
    LEFT JOIN open_q2  AS o USING (product_line)
),
with_total AS (
    SELECT * FROM lines
    UNION ALL
    SELECT 'Total', SUM(q2_budget_revenue_usd), SUM(q1_actual_revenue_usd), SUM(gap_usd),
           SUM(open_opportunities), SUM(open_pipeline_usd), SUM(weighted_pipeline_usd),
           SUM(weighted_revenue_in_quarter_usd)
    FROM lines
)
SELECT
    *,
    CASE WHEN gap_usd > 0 THEN weighted_revenue_in_quarter_usd / gap_usd END AS coverage_ratio
FROM with_total;


/* -----------------------------------------------------------------------------
   10. Opportunity sizing: value of each candidate action, ranked
       value = revenue affected x realistic improvement x operating margin
       "realistic" = the median of the better half of peers, not the single best one
         Invest       -> growth gap to the target, valued at the line's own margin
         Optimise     -> margin gap to the target (pricing / cost of revenue)
         Deprioritise -> margin gap to the target (cost reduction)
         Maintain     -> protect the cash, no extra investment (value 0)
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_opportunity_sizing AS
WITH peers AS (
    SELECT 'Product line' AS level, product_line AS entity, revenue_usd, revenue_growth, operating_margin, portfolio_action
    FROM v_portfolio_fy26
    UNION ALL
    SELECT level, region, revenue_usd, revenue_growth, operating_margin, portfolio_action
    FROM v_portfolio_region_fy26
),
medians AS (
    SELECT level, MEDIAN(operating_margin) AS med_margin, MEDIAN(revenue_growth) AS med_growth
    FROM peers GROUP BY 1
),
targets AS (
    SELECT p.level,
           MEDIAN(p.operating_margin) FILTER (WHERE p.operating_margin >= m.med_margin) AS target_margin,
           MEDIAN(p.revenue_growth)   FILTER (WHERE p.revenue_growth   >= m.med_growth) AS target_growth
    FROM peers AS p JOIN medians AS m USING (level)
    GROUP BY 1
),
valued AS (
    SELECT
        p.*, t.target_growth, t.target_margin,
        GREATEST(t.target_margin - p.operating_margin, 0) * p.revenue_usd                                    AS margin_uplift_usd,
        GREATEST(t.target_growth - p.revenue_growth, 0) * p.revenue_usd * GREATEST(p.operating_margin, 0)    AS growth_uplift_usd
    FROM peers AS p JOIN targets AS t USING (level)
)
SELECT
    *,
    CASE portfolio_action
         WHEN 'Invest'       THEN growth_uplift_usd
         WHEN 'Optimise'     THEN margin_uplift_usd
         WHEN 'Deprioritise' THEN margin_uplift_usd
         ELSE 0 END                                                    AS opportunity_value_usd,
    RANK() OVER (ORDER BY CASE portfolio_action
                              WHEN 'Invest'       THEN growth_uplift_usd
                              WHEN 'Optimise'     THEN margin_uplift_usd
                              WHEN 'Deprioritise' THEN margin_uplift_usd
                              ELSE 0 END DESC)                         AS value_rank
FROM valued
ORDER BY value_rank;


/* -----------------------------------------------------------------------------
   11. Forecast input: total monthly revenue (USD) with fiscal labels, Jan 2024 - Dec 2026.
       06_forecast.ipynb fits: revenue = trend x month_index + fiscal-month effect.
       sample: 'train' up to Mar 2026, 'holdout' = the last two quarters (Apr - Sep 2026)
       for the back-test, 'forecast' = Q2 FY27 (Oct - Dec 2026, no actuals yet).
       Budget revenue is kept beside it as a cross-check.
   ----------------------------------------------------------------------------- */
CREATE OR REPLACE VIEW v_forecast_input AS
WITH months AS (
    SELECT DISTINCT month_start, fiscal_year, fiscal_year_quarter, fiscal_period
    FROM dim_date
    WHERE month_start <= DATE '2026-12-01'
),
actual AS (
    SELECT month_start, SUM(revenue_usd) AS revenue_usd FROM v_revenue_monthly GROUP BY 1
),
budget AS (
    SELECT month_start, SUM(amount_usd) AS budget_revenue_usd
    FROM fact_budget WHERE version = 'Budget' AND line_item = 'Revenue' GROUP BY 1
)
SELECT
    m.month_start,
    date_diff('month', DATE '2024-01-01', m.month_start) + 1           AS month_index,
    m.fiscal_year,
    m.fiscal_year_quarter,
    m.fiscal_period,
    a.revenue_usd,
    b.budget_revenue_usd,
    CASE WHEN m.month_start > DATE '2026-09-01' THEN 'forecast'
         WHEN m.month_start >= DATE '2026-04-01' THEN 'holdout'
         ELSE 'train' END                                              AS sample
FROM months AS m
LEFT JOIN actual AS a USING (month_start)
LEFT JOIN budget AS b USING (month_start)
ORDER BY m.month_start;


