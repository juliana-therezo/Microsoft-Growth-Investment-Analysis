/* =============================================================================
   01_build_star_schema.sql
   Where to Invest: Microsoft Growth Investment Analysis

   Step 4 of the workflow - MODEL (SQL: DuckDB)
   Loads the clean tables written by notebooks/02_cleaning.ipynb (the CSV files in data/clean)
   and builds the star schema: facts around shared dimensions.

       Dimensions : dim_date (built here), dim_product, dim_product_line, dim_region,
                    dim_cloud_region, dim_customer, dim_cost_center
       Facts      : fact_billing, fact_gl_cost, fact_depreciation, fact_datacenter,
                    fact_budget, fact_opportunity
       Reference  : fx_rates

   No cleaning happens here - formats, USD conversion, credit-memo restatement, GL reversals,
   the segment restatement, the CRM country mapping and the budget unpivot are done in Python.

   SYNTHETIC DATA, CALIBRATED TO MICROSOFT'S PUBLISHED RESULTS - generated by data/generate.py.
   Totals are close to Microsoft's reported figures; every record underneath them is invented.

   Run from the project root (the folder that contains data/, notebooks/ and sql/):
       duckdb data/finance.duckdb -c ".read sql/01_build_star_schema.sql"
   ============================================================================= */


/* -----------------------------------------------------------------------------
   1. DIMENSIONS
   ----------------------------------------------------------------------------- */

-- Date: one row per day, Jan 2024 - Jun 2027 (the data window plus the rest of FY27,
-- so the budget and the open pipeline have dates too).
-- Fiscal year runs July - June: FY26 = Jul 2025 - Jun 2026, P01 = July, Q1 = Jul - Sep.
CREATE OR REPLACE TABLE dim_date AS
WITH days AS (
    SELECT CAST(d AS DATE) AS calendar_date
    FROM generate_series(DATE '2024-01-01', DATE '2027-06-30', INTERVAL 1 DAY) AS t(d)
),
fiscal AS (
    SELECT
        calendar_date,
        year(calendar_date)                                        AS calendar_year,
        month(calendar_date)                                       AS calendar_month,
        monthname(calendar_date)                                   AS month_name,
        CAST(date_trunc('month', calendar_date) AS DATE)           AS month_start,
        year(calendar_date) + CASE WHEN month(calendar_date) >= 7 THEN 1 ELSE 0 END AS fiscal_year_num,
        (month(calendar_date) + 5) % 12 + 1                        AS fiscal_period,   -- July = 1
        calendar_date = last_day(calendar_date)                    AS is_month_end,
        dayofweek(calendar_date) IN (0, 6)                         AS is_weekend
    FROM days
)
SELECT
    *,
    'FY' || right(CAST(fiscal_year_num AS VARCHAR), 2)                           AS fiscal_year,      -- FY26
    'Q' || CAST((fiscal_period - 1) // 3 + 1 AS VARCHAR)                         AS fiscal_quarter,   -- Q1
    'FY' || right(CAST(fiscal_year_num AS VARCHAR), 2) || '-Q'
        || CAST((fiscal_period - 1) // 3 + 1 AS VARCHAR)                         AS fiscal_year_quarter,  -- FY26-Q1
    'FY' || right(CAST(fiscal_year_num AS VARCHAR), 2) || '-P'
        || lpad(CAST(fiscal_period AS VARCHAR), 2, '0')                          AS fiscal_year_period,   -- FY26-P01
    CASE WHEN month_start <  DATE '2026-09-01' THEN 'Closed'
         WHEN month_start =  DATE '2026-09-01' THEN 'Open'
         ELSE 'Future' END                                                       AS period_status
FROM fiscal;

-- Product: one row per material and validity period
-- segment = as reported on that date; segment_restated = current segment for every period
CREATE OR REPLACE TABLE dim_product AS
SELECT *
FROM read_csv('data/clean/products.csv', header = true,
              types = {'material': 'VARCHAR', 'valid_from': 'VARCHAR', 'valid_to': 'VARCHAR'});

-- Product line: one row per product line (used by GL costs, budget and pipeline)
CREATE OR REPLACE TABLE dim_product_line AS
SELECT DISTINCT product_line, profit_center, segment_restated, revenue_type
FROM dim_product;

-- Region: country -> sales area -> sales region
CREATE OR REPLACE TABLE dim_region AS
SELECT *
FROM read_csv('data/clean/regions.csv', header = true);

-- Cloud region: datacenter regions (Azure capacity and capex)
CREATE OR REPLACE TABLE dim_cloud_region AS
SELECT DISTINCT d.region_code, d.region_name, d.country_key, r.sales_region
FROM read_csv('data/clean/datacenter.csv', header = true) AS d
LEFT JOIN dim_region AS r USING (country_key);

-- Customer: billed customers (from ERP) plus CRM prospects; customer_id = ERP sold-to party
CREATE OR REPLACE TABLE dim_customer AS
SELECT *
FROM read_csv('data/clean/customers.csv', header = true,
              types = {'customer_id': 'VARCHAR'});

-- Cost centre: the distinct cost centres in the GL. Datacenter cost centres carry their cloud region.
CREATE OR REPLACE TABLE dim_cost_center AS
SELECT
    cost_center_id,
    any_value(cost_center_name)            AS cost_center_name,
    any_value(product_line)                AS product_line,
    any_value(region_code)                 AS region_code,
    CASE split_part(any_value(cost_center_name), '-', 2)
         WHEN 'COR' THEN 'Cost of Revenue'
         WHEN 'DCO' THEN 'Datacenter Operations'
         WHEN 'RND' THEN 'Research and Development'
         WHEN 'SAM' THEN 'Sales and Marketing'
         WHEN 'GNA' THEN 'General and Administrative' END AS function
FROM read_csv('data/clean/gl_costs.csv', header = true,
              types = {'cost_center_id': 'VARCHAR'})
WHERE cost_center_id IS NOT NULL
GROUP BY cost_center_id;

-- FX rates (kept for reference; every fact already carries its USD amount)
CREATE OR REPLACE TABLE fx_rates AS
SELECT *
FROM read_csv('data/clean/fx_rates.csv', header = true);


/* -----------------------------------------------------------------------------
   2. FACTS
   ----------------------------------------------------------------------------- */

-- Billing: one row per invoice or credit-memo line (revenue proxy)
--   month_start   = month booked (cash view)
--   revenue_month = month of the original invoice (margin view; differs only for credit memos)
CREATE OR REPLACE TABLE fact_billing AS
SELECT
    billing_document,
    item,
    billing_type,
    is_credit_memo,
    billing_date,
    month_start,
    revenue_month,
    original_billing_date,
    customer_id,
    country_key,
    material,
    product_line,
    profit_center,
    segment_as_reported,
    segment_restated,
    region_code,
    quantity,
    sales_unit,
    currency,
    net_value_local,
    fx_rate,
    net_value_usd,
    reference_document
FROM read_csv('data/clean/billing.csv', header = true,
              types = {'billing_document': 'VARCHAR', 'item': 'VARCHAR', 'customer_id': 'VARCHAR',
                       'material': 'VARCHAR', 'reference_document': 'VARCHAR'});

-- GL costs: one row per ledger line; month = fiscal period (not posting date)
CREATE OR REPLACE TABLE fact_gl_cost AS
SELECT
    company_code,
    document_number,
    document_type,
    posting_date,
    fiscal_year_num,
    fiscal_period,
    month_start,
    is_late_posting,
    gl_account,
    gl_account_text,
    cost_center_id,
    profit_center,
    product_line,
    region_code,                                      -- filled for datacenter cost centres
    functional_area,
    currency,
    amount_local,
    fx_rate,
    amount_usd,
    posting_text,
    reversed_with
FROM read_csv('data/clean/gl_costs.csv', header = true,
              types = {'document_number': 'VARCHAR', 'gl_account': 'VARCHAR',
                       'cost_center_id': 'VARCHAR', 'reversed_with': 'VARCHAR'});

-- Depreciation: datacenter asset depreciation (GL account 500300) per cloud region x month
CREATE OR REPLACE TABLE fact_depreciation AS
SELECT
    region_code,
    month_start,
    SUM(amount_usd)                                   AS depreciation_usd
FROM fact_gl_cost
WHERE gl_account = '500300'
GROUP BY region_code, month_start;

-- Datacenter: one row per cloud region x month - capex (owned and leased) and capacity
CREATE OR REPLACE TABLE fact_datacenter AS
SELECT
    region_code,
    month_start,
    capex_build_usd,
    capex_fleet_usd,
    capex_network_usd,
    capex_usd,
    capex_finance_lease_usd,
    capex_owned_usd,
    installed_mw,
    used_mw,
    utilization,
    new_capacity_mw,
    availability
FROM read_csv('data/clean/datacenter.csv', header = true);

-- Budget: one row per version x product line x line item x month, USD
CREATE OR REPLACE TABLE fact_budget AS
SELECT *
FROM read_csv('data/clean/budget.csv', header = true);

-- Pipeline: one row per opportunity (customer type and country come from the CRM itself)
CREATE OR REPLACE TABLE fact_opportunity AS
SELECT
    opportunity_id,
    topic,
    customer_id,
    customer_type,
    country_key,
    product_line,
    opportunity_type,
    status,
    status_reason,
    sales_stage,
    probability,
    created_on,
    est_close_date,
    actual_close_date,
    close_date,
    date_diff('day', created_on, close_date)          AS sales_cycle_days,
    currency,
    est_revenue_local,
    est_revenue_usd,
    weighted_revenue_usd,
    owner
FROM read_csv('data/clean/opportunities.csv', header = true,
              types = {'customer_id': 'VARCHAR'});


/* -----------------------------------------------------------------------------
   3. CHECKS - each "problems" value should be 0
   ----------------------------------------------------------------------------- */

SELECT 'fact_billing rows'                       AS check_name, COUNT(*) AS value FROM fact_billing
UNION ALL SELECT 'fact_gl_cost rows',                         COUNT(*) FROM fact_gl_cost
UNION ALL SELECT 'fact_datacenter rows',                      COUNT(*) FROM fact_datacenter
UNION ALL SELECT 'fact_opportunity rows',                     COUNT(*) FROM fact_opportunity
UNION ALL SELECT 'problems: billing without customer',        COUNT(*) FROM fact_billing     WHERE customer_id NOT IN (SELECT customer_id FROM dim_customer)
UNION ALL SELECT 'problems: billing without product',         COUNT(*) FROM fact_billing     WHERE material NOT IN (SELECT material FROM dim_product)
UNION ALL SELECT 'problems: billing month not in dim_date',   COUNT(*) FROM fact_billing     WHERE month_start NOT IN (SELECT calendar_date FROM dim_date)
UNION ALL SELECT 'problems: GL month not in dim_date',        COUNT(*) FROM fact_gl_cost     WHERE month_start NOT IN (SELECT calendar_date FROM dim_date)
UNION ALL SELECT 'problems: datacenter region not in dimension', COUNT(*) FROM fact_datacenter WHERE region_code NOT IN (SELECT region_code FROM dim_cloud_region)
UNION ALL SELECT 'problems: opportunity without country',     COUNT(*) FROM fact_opportunity WHERE country_key IS NULL
UNION ALL SELECT 'info: depreciation rows with no region (blank cost centre)', COUNT(*) FROM fact_depreciation WHERE region_code IS NULL;
